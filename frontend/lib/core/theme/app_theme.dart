import '../../shared/widgets/app_back_button.dart';
import 'package:flutter/material.dart';
import 'material_theme.dart';

/// Application theme definitions implementing Material 3 consistently across the app.
/// Based on Google Material Theme Builder design tokens (Green Primary).
class AppTheme {
  // Primary Green Palette Tokens
  static const Color primaryColor = Color(0xFF2E6A44);
  static const Color onPrimaryColor = Color(0xFFFFFFFF);

  // Surface Tokens
  static const Color surfaceColor = Color(0xFFF6FBF3);
  static const Color surfaceContainerColor = Color(0xFFEAEFE8);

  // Content & Text Tokens
  static const Color onSurfaceColor = Color(0xFF181D18);
  static const Color onSurfaceVariantColor = Color(0xFF414942);
  static const Color outlineColor = Color(0xFF717971);

  // Light Scheme generated by Material 3 Theme Builder
  static ColorScheme get lightColorScheme => MaterialTheme.lightScheme();

  // Dark Scheme generated by Material 3 Theme Builder
  static ColorScheme get darkColorScheme => MaterialTheme.darkScheme();

  static ThemeData get lightTheme {
    const textTheme = Typography.blackMountainView;
    final materialTheme = MaterialTheme(textTheme.apply(fontFamily: 'Sarabun'));
    final base = materialTheme.light();

    return base.copyWith(
      scaffoldBackgroundColor: lightColorScheme.surface,
      appBarTheme: AppBarTheme(
        backgroundColor: lightColorScheme.surface,
        foregroundColor: lightColorScheme.onSurface,
        elevation: 0,
        centerTitle: false,
        titleTextStyle: const TextStyle(
          color: Color(0xFF1A201C),
          fontSize: 22,
          fontWeight: FontWeight.w800,
          letterSpacing: -0.5,
        ),
      ),
      floatingActionButtonTheme: FloatingActionButtonThemeData(
        backgroundColor: const Color(0xFF2E6A44),
        foregroundColor: Colors.white,
        elevation: 4,
        shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(20)),
      ),
      actionIconTheme: ActionIconThemeData(
        backButtonIconBuilder: (BuildContext context) {
          return const AppBackButton();
        },
      ),
      elevatedButtonTheme: ElevatedButtonThemeData(
        style: ElevatedButton.styleFrom(
          backgroundColor: lightColorScheme.primary,
          foregroundColor: lightColorScheme.onPrimary,
          minimumSize: const Size.fromHeight(50),
          shape: const StadiumBorder(),
          elevation: 0,
        ),
      ),
      inputDecorationTheme: InputDecorationTheme(
        filled: true,
        fillColor: lightColorScheme.surfaceContainer,
        contentPadding: const EdgeInsets.symmetric(horizontal: 20, vertical: 16),
        border: OutlineInputBorder(
          borderRadius: BorderRadius.circular(28),
          borderSide: BorderSide.none,
        ),
      ),
    );
  }

  static ThemeData get darkTheme {
    const textTheme = Typography.whiteMountainView;
    final materialTheme = MaterialTheme(textTheme.apply(fontFamily: 'Sarabun'));
    final base = materialTheme.dark();

    return base.copyWith(
      scaffoldBackgroundColor: darkColorScheme.surface,
      appBarTheme: AppBarTheme(
        backgroundColor: darkColorScheme.surface,
        foregroundColor: darkColorScheme.onSurface,
        elevation: 0,
        centerTitle: false,
      ),
      floatingActionButtonTheme: FloatingActionButtonThemeData(
        backgroundColor: const Color(0xFF2E6A44),
        foregroundColor: Colors.white,
        elevation: 4,
        shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(20)),
      ),
      elevatedButtonTheme: ElevatedButtonThemeData(
        style: ElevatedButton.styleFrom(
          backgroundColor: darkColorScheme.primary,
          foregroundColor: darkColorScheme.onPrimary,
          minimumSize: const Size.fromHeight(50),
          shape: const StadiumBorder(),
          elevation: 0,
        ),
      ),
    );
  }
}
